"""練習用の合成 DSC データ（Pyris のテキスト書き出しと同じ形）を DATA/ に書く。

中身は作りもの。Comment 行に SYNTHETIC と書いてある。台帳・解析・ギャラリーの流れを試すためのもの。

- 二つの架空の試料（ExampleFat-A / ExampleFat-B）
- 熱履歴: 25→80@10 > hold80/5min > 80→Ta@10 > holdTa/30min > Ta→80@5
- 保持中に結晶化（Avrami 型、Ta が高いほど遅い）、最後の昇温で融解（Ta が低いと低融点の相）
- わざと仕込んだもの: バックアップのコピー 1 本（duplicates の例）、試料名が空の 1 本（gaps の例）、
  質量の打ち間違い 1 本（ledger_fixes.csv の例）
"""
from __future__ import annotations

import math
import os
import random
from datetime import datetime, timedelta

RUNS = [  # (試料, Ta, 質量, 日時)
    ("ExampleFat-A", 20, 4.12, "2025-04-14 09:52:25"),
    ("ExampleFat-A", 25, 4.08, "2025-04-14 11:30:02"),
    ("ExampleFat-A", 30, 4.15, "2025-04-14 13:41:47"),
    ("ExampleFat-A", 35, 4.10, "2025-04-15 10:05:13"),
    ("ExampleFat-A", 40, 1.06, "2025-04-15 12:20:40"),   # 質量の打ち間違い（本当は 4.06）
    ("ExampleFat-B", 15, 3.95, "2025-05-02 10:12:08"),
    ("ExampleFat-B", 25, 4.01, "2025-05-02 12:48:31"),
    ("", 30, 3.98, "2025-05-02 15:02:56"),               # 試料名の入れ忘れ
]
DT = 0.1  # min


def _program(Ta: float):
    return [("Heat", 25, 80, 10), ("Hold", 80, 5), ("Cool", 80, Ta, 10), ("Hold", Ta, 30), ("Heat", Ta, 80, 5)]


def _curve(sample: str, Ta: float, mass: float, rng: random.Random):
    prog = _program(Ta)
    B = sample.endswith("B")
    t_ind = 1.5 + 0.18 * (Ta - 15) ** 1.4 / (3 if B else 1)     # 誘導時間 [min]
    k = 0.45 / (1 + 0.08 * (Ta - 15))
    n = 2.6
    Tm = (52.0 if Ta >= 25 else 44.0) + (3.0 if B else 0.0)    # 融点 [°C]
    dH = 9.0 * mass                                            # 結晶化の発熱の大きさ（任意単位）
    rows, t, T = [], 0.0, 25.0
    hold_start = None
    for step in prog:
        if step[0] == "Hold":
            dur = step[2]
            steps = int(round(dur / DT))
            if step[1] == Ta:
                hold_start = t
            for i in range(steps):
                hf = 0.0
                if hold_start is not None and step[1] == Ta:
                    tau = t - hold_start
                    if tau > t_ind:
                        x = k * (tau - t_ind)
                        hf = -dH * n * k * x ** (n - 1) * math.exp(-x ** n) * 0.25
                    hf += -0.6 * math.exp(-tau / 0.4)          # 保持に入った直後の装置の過渡
                rows.append((t, T, hf))
                t += DT
        else:
            _, a, b, rate = step
            steps = int(round(abs(b - a) / rate / DT))
            for i in range(steps):
                T = a + (b - a) * i / steps
                hf = 0.004 * (T - 25) * (1 if b > a else -1)
                if hold_start is not None and b > a:           # 最後の昇温: 融解
                    hf += dH * 0.12 * math.exp(-((T - Tm) / 1.6) ** 2)
                rows.append((t, T, hf))
                t += DT
            T = b
    out = []
    for t, Tp, hf in rows:
        base = 20.0 + 0.02 * Tp
        noise = rng.gauss(0, 0.01)
        out.append((t, base + hf + noise, 0.0, Tp, Tp - 0.5, base + hf + noise))
    return prog, out


def _fmt_step(i, s):
    if s[0] == "Hold":
        return "%d)\tHold for %.1f min at %.2f°C " % (i, s[2], s[1])
    return "%d)\t%s from %.2f°C to %.2f°C at %.2f°C/min " % (i, s[0], s[1], s[2], s[3])


def write_run(path: str, sample: str, Ta: float, mass: float, when: str, seed: int):
    rng = random.Random(seed)
    prog, rows = _curve(sample or "X", Ta, mass if mass > 2 else mass + 3.0, rng)
    dt = datetime.strptime(when, "%Y-%m-%d %H:%M:%S")
    stem = os.path.splitext(os.path.basename(path))[0]
    lines = [
        "Filename:\tC:\\Pyris\\data\\example\\%s.ds8d " % stem,
        "Operator ID:\texample ",
        "Sample ID:\t%s " % sample,
        "Comment: \tSYNTHETIC EXAMPLE generated by labkit (not a real measurement)",
        "Data Collected:\t%s " % dt.strftime("%d/%m/%Y %H:%M:%S"),
        "Sample Weight:\t%.3f mg " % mass,
        "Method Steps: ",
    ]
    for i, s in enumerate(prog, 1):
        lines += [_fmt_step(i, s), " "]
    lines += [
        "1) DSC Temperature Scan ",
        "\tTime     \tUnsubtracted\tBaseline     \tProgram     \tSample     \tHeat Flow     ",
        "\t          \tHeat Flow     \tHeat Flow     \tTemperature\tTemperature\t               ",
    ]
    for r in rows:
        lines.append("\t" + "\t".join("%.6f" % v for v in r) + " ")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="latin-1", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")


def write_all(data_dir: str) -> list[str]:
    paths = []
    for i, (sample, Ta, mass, when) in enumerate(RUNS, 1):
        month = when[:7]
        name = "%02d-%s_Ta%d.txt" % (i, (sample or "unknown").replace("ExampleFat-", "fat"), Ta)
        p = os.path.join(data_dir, "dsc", month, name)
        write_run(p, sample, Ta, mass, when, seed=i)
        paths.append(p)
    # バックアップのコピー（同じ測定）
    src = paths[1]
    dst = os.path.join(data_dir, "dsc", "backup", os.path.basename(src))
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(src, "rb") as f, open(dst, "wb") as g:
        g.write(f.read())
    paths.append(dst)
    with open(os.path.join(data_dir, "dsc", "README.md"), "w", encoding="utf-8") as f:
        f.write("# DATA/dsc（練習用）\n\nlabkit が作った合成データ。実際の測定ではない。\n"
                "`backup/` は 2025-04 の 1 本のコピー（台帳では duplicates 列に入る）。\n")
    return paths


